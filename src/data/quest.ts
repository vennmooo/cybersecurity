export const MAX_SCORE = 170;

export function computeStatus(percentage: number): string {
  if (percentage >= 85) return 'Цифровой детектив';
  if (percentage >= 60) return 'Стажёр детектива';
  if (percentage >= 40) return 'Новичок';
  return 'Нужна подготовка';
}

